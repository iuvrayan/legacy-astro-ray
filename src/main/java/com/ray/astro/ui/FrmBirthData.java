    private void clearLatitudeAndLogitude() {
        txfLatitude.setText("00:00:00:N");
        txfLongitude.setText("00:00:00:E");
    }

    private void setLatitudeAndLogitude(String location) {
        try {
            txtLocation.setText(location);

            String[] latLon = application.getLocationDAO().getLatitudeAndLongitude(location);
            if (latLon == null) {
                clearLatitudeAndLogitude();
                JOptionPane.showMessageDialog(this, "Location " + location + " not found in the Database");
            } else {
                txfLatitude.setText(latLon[0]);
                txfLongitude.setText(latLon[1]);
            }
        } catch (AstroRayAppException e) {
            clearLatitudeAndLogitude();
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }

    public void setLocLatLon(String location, String latitude, String longitude) {
        txtLocation.setText(location);
        txfLatitude.setText(latitude);
        txfLongitude.setText(longitude);
    }

    private void btnOKActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnOKActionPerformed
        try {
            String message = application.prepareHoroscope(getBirthData());
            JOptionPane.showMessageDialog(this, message);

            //Store the Location details in astroray_latlon.dat file if not found
            try {
                if (application.getLocationDAO().getMatchingLocations(txtLocation.getText().trim().toUpperCase()) == null) {
                    application.getLocationDAO().addLocation(txtLocation.getText().trim().toUpperCase(), txfLatitude.getText().trim(), txfLongitude.getText().trim());
                }
            } catch (AstroRayAppException aep) {
                JOptionPane.showMessageDialog(this, aep.getMessage());
            }

            //View the PDF file using Adobe Acrobat Reader
            application.viewPdfFile();

        } catch (AstroRayAppException ae) {
            JOptionPane.showMessageDialog(null, ae.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnOKActionPerformed

    private void btnCancelActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCancelActionPerformed
        setVisible(false);
        try {
            application.getLocationDAO().closeDB();
        } catch (AstroRayAppException e) {
            JOptionPane.showMessageDialog(null, e.getMessage(), "Not able to close Database Connection", JOptionPane.ERROR_MESSAGE);
        }
        System.exit(0);
    }//GEN-LAST:event_btnCancelActionPerformed

