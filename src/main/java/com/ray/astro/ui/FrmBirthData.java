    private BirthData getBirthData() {
        BirthData birthData = new BirthData();

        birthData.setName(txtName.getText());

        String[] dateTokens = txfDate.getText().split("-");
        birthData.setDay(Integer.parseInt(dateTokens[0]));
        birthData.setMonth(Integer.parseInt(dateTokens[1]));
        birthData.setYear(Integer.parseInt(dateTokens[2]));
        
        String[] timeTokens = txfTime.getText().split(":");
        birthData.setHours(Integer.parseInt(timeTokens[0]));
        birthData.setMinutes(Integer.parseInt(timeTokens[1]));
        birthData.setSeconds(Integer.parseInt(timeTokens[2]));
        birthData.setMeridian(timeTokens[3]);

        birthData.setLocationName(txtLocation.getText());

        
        String[] latitudeTokens = txfLatitude.getText().split(":");
        birthData.setLatitudeDegrees(Integer.parseInt(latitudeTokens[0]));
        birthData.setLatitudeMinutes(Integer.parseInt(latitudeTokens[1]));
        birthData.setLatitudeSeconds(Integer.parseInt(latitudeTokens[2]));
        if (latitudeTokens[3].equalsIgnoreCase("N")) {
            birthData.setLatitudeDirection(BirthData.NORTH);
        } else if (latitudeTokens[3].equalsIgnoreCase("S")) {
            birthData.setLatitudeDirection(BirthData.SOUTH);
        }

       
        String[] longitudeTokens = txfLongitude.getText().split(":");
        birthData.setLongitudeDegrees(Integer.parseInt(longitudeTokens[0]));
        birthData.setLongitudeMinutes(Integer.parseInt(longitudeTokens[1]));
        birthData.setLongitudeSeconds(Integer.parseInt(longitudeTokens[2]));
        if (longitudeTokens[3].equalsIgnoreCase("E")) {
            birthData.setLongitudeDirection(BirthData.EAST);
        } else if (longitudeTokens[3].equalsIgnoreCase("W")) {
            birthData.setLongitudeDirection(BirthData.WEST);
        }

        String[] timeZoneTokens = txfTimeZone.getText().split(":");
        if (timeZoneTokens[0].charAt(0) == '+') {
            birthData.setTimeZoneDirection(BirthData.EAST);
        } else {
            birthData.setTimeZoneDirection(BirthData.WEST);
        }        
        birthData.setTimeZoneHours(Integer.parseInt(timeZoneTokens[0].substring(2, 4)));
        birthData.setTimeZoneMinutes(Integer.parseInt(timeZoneTokens[1]));
        birthData.setTimeZoneSeconds(Integer.parseInt(timeZoneTokens[2]));

        birthData.setInDST(chkDST.isSelected());        
        String[] dstTokens = txfDST.getText().split(":");
        birthData.setDstHours(Integer.parseInt(dstTokens[0]));
        birthData.setDstMinutes(Integer.parseInt(dstTokens[1]));
        birthData.setDstSeconds(Integer.parseInt(dstTokens[2]));

        birthData.setIsMoonGiven(chkMoon.isSelected());        
        String[] moonTokens = txfMoon.getText().split(":");
        birthData.setMoonSign(Integer.parseInt(moonTokens[0]));
        birthData.setMoonDegrees(Integer.parseInt(moonTokens[1]));
        birthData.setMoonMinutes(Integer.parseInt(moonTokens[2]));
        birthData.setMoonSeconds(Integer.parseInt(moonTokens[3]));

        birthData.setRemarks(txaRemarks.getText());

        return birthData;
    }

