    private void btnModifyActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModifyActionPerformed

        try {
            String oldLocation = lstLocations.getSelectedValue().toString();
            String newLocation = txtLocation.getText().trim().toUpperCase();
            String latitude = txfLatitude.getText();
            String longitude = txfLongitude.getText();

            if (!newLocation.equals("") && !latitude.startsWith("00:00:00") && !longitude.startsWith("00:00:00")) {

                if (newLocation.equals(currentLocation) && latitude.equals(currentLatitude) && longitude.equals(currentLongitude)) {
                    JOptionPane.showMessageDialog(this, "No Modifications found");
                    return;
                }
                
                int modifyingIndex = lstLocations.getSelectedIndex();

                locationDAO.modifyLocation(oldLocation, newLocation, latitude, longitude);
                JOptionPane.showMessageDialog(this, "Location " + newLocation + " got modified successfully");

                DefaultListModel model = (DefaultListModel) lstLocations.getModel();
                model.setElementAt(newLocation, modifyingIndex);
                model.trimToSize();

                lstLocations.setSelectedIndex(modifyingIndex);
                lstLocations.ensureIndexIsVisible(modifyingIndex);
            } else {
                JOptionPane.showMessageDialog(this, "Enter valid values");
            }
        } catch (AstroRayAppException e) {
            JOptionPane.showMessageDialog(null, e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnModifyActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed

        try {
            String location = (String) lstLocations.getSelectedValue();
            int selectedIndex = lstLocations.getSelectedIndex();

            if (location == null || selectedIndex == -1) {
                JOptionPane.showMessageDialog(this, "No records to delete");
                return;
            }

            int reply = JOptionPane.showConfirmDialog(this, "Do you really want to Delete?");

            if (reply == JOptionPane.CANCEL_OPTION || reply == JOptionPane.NO_OPTION) {
                return;
            }

            locationDAO.deleteLocation(location);

            DefaultListModel model = (DefaultListModel) lstLocations.getModel();
            model.removeElement(location);
            model.trimToSize();

            if (!model.isEmpty()) {
                if (model.size() == selectedIndex) {
                    selectedIndex = model.size() - 1;
                }
                lstLocations.setSelectedIndex(selectedIndex);
                lstLocations.ensureIndexIsVisible(selectedIndex);

            } else {
                clearTextFields();
            }

            JOptionPane.showMessageDialog(this, "Location " + location + " got deleted successfully");
        } catch (AstroRayAppException e) {
            JOptionPane.showMessageDialog(null, e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

