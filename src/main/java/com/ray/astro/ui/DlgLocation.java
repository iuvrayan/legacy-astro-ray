    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed

        try {
            clearLatitudeAndLongitude();
            txtLocation.setText(txtLocation.getText().toUpperCase().trim());
            String location = txtLocation.getText();

            DefaultListModel model = new DefaultListModel();

            Vector vecLocations = locationDAO.getMatchingLocations(location);
            if (vecLocations != null) {
                for (int i = 0; i < vecLocations.size(); i++) {
                    model.addElement(vecLocations.elementAt(i));
                }
                model.trimToSize();
            }

            lstLocations.setModel(model);

            lstLocations.clearSelection();

            if (!model.isEmpty()) {
                if (location.contains("%")) {
                    lstLocations.setSelectedIndex(0);
                    lstLocations.ensureIndexIsVisible(0);
                } else {
                    lstLocations.setSelectedValue(location, true);
                }
            } else {
                JOptionPane.showMessageDialog(this, "No matching records found");
            }
        } catch (AstroRayAppException e) {
            JOptionPane.showMessageDialog(null, e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
}//GEN-LAST:event_btnSearchActionPerformed

