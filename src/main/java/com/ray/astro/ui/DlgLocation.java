    private void lstLocationsValueChanged(javax.swing.event.ListSelectionEvent evt) {//GEN-FIRST:event_lstLocationsValueChanged

        try {
            if (lstLocations.getSelectedIndex() < 0) {
                clearTextFields();
                return;
            }
            
            String location = (String)lstLocations.getSelectedValue();

            if (location == null) {
                clearTextFields();
                return;
            }

            location = location.toString().trim();

            if (location.equals("")) {
                clearTextFields();
                return;
            }
            
            String[] latLon = locationDAO.getLatitudeAndLongitude(location);
            if (latLon != null) {
                txtLocation.setText(location);
                txfLatitude.setText(latLon[0]);
                txfLongitude.setText(latLon[1]);

                currentLocation = location;
                currentLatitude = latLon[0];
                currentLongitude = latLon[1];
            }
        } catch (AstroRayAppException e) {
            JOptionPane.showMessageDialog(null, e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
}//GEN-LAST:event_lstLocationsValueChanged

